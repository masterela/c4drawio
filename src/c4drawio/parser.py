"""Parse a .drawio file back into a Document (and YAML).

Cells generated by c4drawio carry their model in attributes (c4Kind, c4Name, c4Technology, ...), the same
placeholder convention as draw.io's own C4 shapes. Cells added by hand in draw.io become `kind: raw` elements
(label + style + geometry) and plain edges become relationships, so nothing is lost on a round-trip.
"""

from __future__ import annotations

import base64
import json
import re
import urllib.parse
import xml.etree.ElementTree as ET
import zlib
from pathlib import Path

from .model import BOUNDARY_KINDS, LEAF_KINDS, Document, Node, Page, Relationship

_BR = re.compile(r"<br\s*/?>", re.I)
_TAG = re.compile(r"<[^>]+>")


def _from_html(s: str | None) -> str:
    if not s:
        return ""
    s = _BR.sub("\n", s)
    return s.replace("&nbsp;", " ").strip()


def _plain(s: str | None) -> str:
    return _TAG.sub("", _from_html(s)).replace("&amp;", "&").replace("&lt;", "<").replace("&gt;", ">")


def _model(diagram: ET.Element) -> ET.Element | None:
    m = diagram.find("mxGraphModel")
    if m is not None:
        return m
    text = (diagram.text or "").strip()
    if not text:
        return None
    raw = zlib.decompress(base64.b64decode(text), -15).decode("utf-8")
    return ET.fromstring(urllib.parse.unquote(raw))


def _cells(model: ET.Element) -> list[dict]:
    root = model.find("root")
    out = []
    for el in list(root) if root is not None else []:
        if el.tag in ("object", "UserObject"):
            attrs = dict(el.attrib)
            cell = el.find("mxCell")
            if cell is None:
                continue
            cid, label = attrs.pop("id", ""), attrs.pop("label", "")
        elif el.tag == "mxCell":
            attrs, cell = {}, el
            cid, label = el.get("id", ""), el.get("value", "")
        else:
            continue
        geo = cell.find("mxGeometry")
        g = {k: float(geo.get(k, 0) or 0) for k in ("x", "y", "width", "height")} if geo is not None else {}
        out.append({"id": cid, "label": label, "attrs": attrs, "style": cell.get("style", ""),
                    "parent": cell.get("parent"), "vertex": cell.get("vertex") == "1",
                    "edge": cell.get("edge") == "1", "source": cell.get("source"), "target": cell.get("target"),
                    "visible": cell.get("visible") != "0", "geo": g})
    return out


def _json(v: str | None, default):
    if v in (None, ""):
        return default
    try:
        return json.loads(v)
    except (ValueError, TypeError):
        return v


def _page(name: str, model: ET.Element, keep_layout: bool) -> tuple[Page, str | None, dict]:
    cells = _cells(model)
    root = Node(id="__page__", kind="page", padding=0)
    page = Page(name=name, root=root)
    theme, overrides = None, {}
    nodes: dict[str, Node] = {}
    pending: list[tuple[Node, str | None]] = []
    for c in cells:
        a, kind = c["attrs"], c["attrs"].get("c4Kind")
        if c["id"] in ("0", "1") or c["edge"]:
            continue
        if kind == "meta":
            theme, overrides = a.get("c4Theme"), _json(a.get("c4ThemeOverrides"), {})
            continue
        if kind == "title":
            page.title = _plain(c["label"])
            continue
        if kind == "subtitle":
            page.subtitle = _plain(c["label"])
            continue
        if kind == "badge" or not c["vertex"]:
            continue
        g = c["geo"]
        if kind not in LEAF_KINDS and kind not in BOUNDARY_KINDS:
            n = Node(id=c["id"], kind="raw", name=c["label"], style=c["style"])
            n.pos, n.size = (g.get("x", 0), g.get("y", 0)), (g.get("width", 0), g.get("height", 0))
        else:
            n = Node(id=c["id"], kind=kind, name=_from_html(a.get("c4Name")),
                     technology=_from_html(a.get("c4Technology")), description=_from_html(a.get("c4Description")),
                     icon=a.get("c4Icon") or None, color=a.get("c4Color") or None,
                     font_color=a.get("c4FontColor") or None, badge=a.get("c4Badge") or None,
                     style=a.get("c4Style") or "")
            if kind in BOUNDARY_KINDS:
                n.layout = a.get("c4Layout", "row")
                n.columns = int(_json(a.get("c4Columns"), 0) or 0)
                n.gap = _json(a.get("c4Gap"), None)
                n.padding = _json(a.get("c4Padding"), None)
                n.align = a.get("c4Align", "start")
                n.justify = a.get("c4Justify", "start")
                n.stretch = bool(_json(a.get("c4Stretch"), True))
            if kind == "icon" and a.get("c4IconSize"):
                s = float(a["c4IconSize"])
                n.size = (s, s)
            if keep_layout:
                n.pos = (g.get("x", 0), g.get("y", 0))
                if kind != "icon":
                    n.size = (g.get("width", 0), g.get("height", 0))
        nodes[n.id] = n
        pending.append((n, c["parent"]))
    for n, parent in pending:
        p = nodes.get(parent) if parent else None
        if p is None or not p.is_boundary:
            p = root
            if keep_layout and n.pos is not None and parent in nodes:
                # parent is a leaf (unusual): keep absolute-ish position under the page
                n.pos = (n.pos[0] + (nodes[parent].pos or (0, 0))[0], n.pos[1] + (nodes[parent].pos or (0, 0))[1])
        n.parent = p
        p.children.append(n)
    for c in cells:
        if not c["edge"] or c["source"] not in nodes or c["target"] not in nodes:
            continue
        a = c["attrs"]
        label = _from_html(a["c4Description"]) if "c4Description" in a else _plain(c["label"])
        page.relationships.append(Relationship(
            id=c["id"], source=c["source"], target=c["target"], label=label,
            technology=_from_html(a.get("c4Technology")), style=a.get("c4Style") or "default",
            color=a.get("c4Color") or None, bidirectional=a.get("c4Bidirectional") == "1"))
    return page, theme, overrides


def parse_drawio(path: str | Path, keep_layout: bool = True) -> Document:
    tree = ET.parse(str(path))
    root = tree.getroot()
    diagrams = [root] if root.tag == "mxGraphModel" else root.findall("diagram")
    pages, theme, overrides = [], None, {}
    for i, d in enumerate(diagrams):
        model = d if d.tag == "mxGraphModel" else _model(d)
        if model is None:
            continue
        page, th, ov = _page(d.get("name") or f"Page {i + 1}", model, keep_layout)
        theme, overrides = theme or th, overrides or ov
        pages.append(page)
    return Document(pages=pages, theme=theme or "c4", theme_overrides=overrides)
